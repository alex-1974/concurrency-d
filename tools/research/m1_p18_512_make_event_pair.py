#!/usr/bin/env python3
"""P18: event-only instrument EXACT unchanged M0 and generated idle-grace.

The only semantic change from each source is passive event counting. The
candidate must first have been generated by P18's reviewed source-pinned
generator. No extra mutex, cross-worker atomic or timing calls are added.
Counters are NOT trustworthy measures of time or portable overhead.
"""
import argparse
import hashlib
from pathlib import Path
import tempfile

from m1_p18_make_grace_pool import generate as generate_exact_grace

M0 = "b7d8fafcb3179f00cba7e89e28c6d6b9b676353a"

def once(source, old, new):
    count = source.count(old)
    if count != 1:
        raise RuntimeError(f"P18 source drift: expected one anchor, found {count}: {old[:110]!r}")
    return source.replace(old, new, 1)

def instrument(path, destination, kind):
    raw = path.read_bytes()
    text = raw.decode("utf8")
    if kind == "control":
        blob = hashlib.sha1(f"blob {len(raw)}\0".encode() + raw).hexdigest()
        if blob != M0:
            raise RuntimeError(f"P18 original M0 changed: {blob}")
        oldmod = "module concurrency.internal.submission_pool;"
        module = "concurrency.research.m1_p18_trace_control_pool"
        count_completed = "_completed"
    else:
        # P18 candidate is a generated exact-source copy of the pinned M0.
        if not text.startswith("// GENERATED P18 BOUNDED IDLE GRACE RESEARCH COPY; NO PRODUCTION EDIT.\n"):
            raise RuntimeError("P18 trace input is not the P18 source-pinned candidate")
        if f"// Original M0 Git blob {M0}\n" not in text[:180]:
            raise RuntimeError("P18 trace candidate M0 lineage mismatch")
        if text.count("private enum size_t P18MaxIdleRetries = 1;") != 1:
            raise RuntimeError("P18 one-retry bound changed")
        # Reproduce the source-pinned candidate from the original M0 and
        # compare exact bytes. Header or isolated anchors are insufficient
        # to establish that a candidate has not been silently modified.
        root = Path(__file__).resolve().parents[2]
        source = root / "source/concurrency/internal/submission_pool.d"
        with tempfile.TemporaryDirectory(prefix="p18-trace-source-") as temp:
            expected = Path(temp) / "m1_p18_grace_pool.d"
            generate_exact_grace(source, expected)
            if raw != expected.read_bytes():
                raise RuntimeError("P18 trace candidate diverges from source-pinned generated bytes")
        oldmod = "module concurrency.research.m1_p18_grace_pool;"
        module = "concurrency.research.m1_p18_trace_grace_pool"
        count_completed = "_completed"

    text = once(text, oldmod, f"""module {module};

// P18 research-only per-worker counters and inbox sleeping-state bins.
// Read only after a successful native worker join.
align(64) private struct P18TraceWorker
{{
    ulong localHits;
    ulong localMisses;
    ulong batchAttempts;
    ulong batchClaims;
    ulong batchTasks;
    ulong stealAttempts;
    ulong stealSuccesses;
    ulong parkAttempts;
    ulong graceSearches;
    ulong graceRecoveredLocal;
    ulong graceRecoveredInbox;
    ulong graceRecoveredSteal;
    ulong graceFallbacks;
    ulong graceDrainExits;
    ulong executed;
}}
struct P18TraceSnapshot
{{
    size_t workerCount;
    ulong localHits;
    ulong localMisses;
    ulong batchAttempts;
    ulong batchClaims;
    ulong batchTasks;
    ulong stealAttempts;
    ulong stealSuccesses;
    ulong parkAttempts;
    ulong graceSearches;
    ulong graceRecoveredLocal;
    ulong graceRecoveredInbox;
    ulong graceRecoveredSteal;
    ulong graceFallbacks;
    ulong graceDrainExits;
    ulong parkWaits;
    ulong parkWaitsNoOutstanding;
    ulong parkWaitsWithOutstanding;
    ulong executed;
    ulong[16] workerExecuted;
}}
""")
    text = once(text,
        """    private size_t _parkCount;
    private bool _closed;""",
        """    private size_t _parkCount;
    private size_t _p18ParkNoOutstanding;
    private size_t _p18ParkWithOutstanding;
    private bool _closed;""")
    text = once(text,
        """                ++_parkCount;
                _changed.wait();""",
        f"""                ++_parkCount;
                // Same existing Condition Mutex protects accepted/queue and
                // the original completed field; the atomic version reads
                // the seq-cst completed counter with its normal protocol.
                const outstanding = _accepted - {count_completed};
                if (outstanding == 0)
                    ++_p18ParkNoOutstanding;
                else
                    ++_p18ParkWithOutstanding;
                _changed.wait();""")
    text = once(text,
        """    size_t parkCount()
    {
        synchronized (_mutex)
        {
            return _parkCount;
        }
    }

    bool isDrained()""",
        """    size_t parkCount()
    {
        synchronized (_mutex)
        {
            return _parkCount;
        }
    }

    void p18TraceRead(ref P18TraceSnapshot result)
    {
        synchronized (_mutex)
        {
            result.parkWaits = _parkCount;
            result.parkWaitsNoOutstanding = _p18ParkNoOutstanding;
            result.parkWaitsWithOutstanding = _p18ParkWithOutstanding;
        }
    }

    bool isDrained()""")
    text = once(text,
        """    private size_t _started;

    // Optional internal completion hook.""",
        """    private size_t _started;
    private P18TraceWorker[] _p18TraceWorkers;

    // Optional internal completion hook.""")
    text = once(text,
        """        _workers = new Thread[workerCount];

        try""",
        """        _workers = new Thread[workerCount];
        _p18TraceWorkers = new P18TraceWorker[workerCount];

        try""")
    text = once(text,
        """    /** Diagnostic only, used by race-oriented parking tests. */
    size_t parkCount()
    {
        return _inbox.parkCount();
    }

    private void executeOne(TaskRef task)""",
        """    /** Diagnostic only, used by race-oriented parking tests. */
    size_t parkCount()
    {
        return _inbox.parkCount();
    }

    P18TraceSnapshot p18TraceSnapshot()
    {
        P18TraceSnapshot result;
        result.workerCount = _p18TraceWorkers.length;
        _inbox.p18TraceRead(result);
        foreach (i, ref worker; _p18TraceWorkers)
        {
            if (i < result.workerExecuted.length)
                result.workerExecuted[i] = worker.executed;
            result.localHits += worker.localHits;
            result.localMisses += worker.localMisses;
            result.batchAttempts += worker.batchAttempts;
            result.batchClaims += worker.batchClaims;
            result.batchTasks += worker.batchTasks;
            result.stealAttempts += worker.stealAttempts;
            result.stealSuccesses += worker.stealSuccesses;
            result.parkAttempts += worker.parkAttempts;
            result.graceSearches += worker.graceSearches;
            result.graceRecoveredLocal += worker.graceRecoveredLocal;
            result.graceRecoveredInbox += worker.graceRecoveredInbox;
            result.graceRecoveredSteal += worker.graceRecoveredSteal;
            result.graceFallbacks += worker.graceFallbacks;
            result.graceDrainExits += worker.graceDrainExits;
            result.executed += worker.executed;
        }
        return result;
    }

    private void executeOne(TaskRef task, size_t self)""")
    text = once(text,
        """        dispatchTask(task);
        _inbox.completeOne();""",
        """        dispatchTask(task);
        _inbox.completeOne();
        ++_p18TraceWorkers[self].executed;""")
    for old, new in (
        ("executeOne(local.value);", "executeOne(local.value, self);"),
        ("executeOne(task);", "executeOne(task, self);"),
        ("executeOne(batch[0]);", "executeOne(batch[0], self);"),
        ("executeOne(stolen.value);", "executeOne(stolen.value, self);"),
    ):
        text = once(text, old, new)
    if kind == "control":
        local_success_prefix = "                executeOne(local.value, self);"
    else:
        # The P18 candidate resets idleRetries before executing local work.
        # Retain that statement exactly; the candidate-specific diagnostic
        # below will count a successful second-pass local recovery.
        local_success_prefix = ("                idleRetries = 0;\n"
                                "                executeOne(local.value, self);")
    text = once(text,
        """            auto local = _queues[self].pop();
            if (local.found)
            {
""" + local_success_prefix + """
                continue;
            }""",
        """            auto local = _queues[self].pop();
            if (local.found)
            {
                ++_p18TraceWorkers[self].localHits;
""" + local_success_prefix + """
                continue;
            }
            ++_p18TraceWorkers[self].localMisses;""")
    text = once(text,
        """            const taken = _inbox.takeBatch(batch[]);
            if (taken != 0)
            {""",
        """            const taken = _inbox.takeBatch(batch[]);
            ++_p18TraceWorkers[self].batchAttempts;
            if (taken != 0)
            {
                ++_p18TraceWorkers[self].batchClaims;
                _p18TraceWorkers[self].batchTasks += taken;""")
    text = once(text,
        """                auto stolen = _queues[victim].steal();

                if (!stolen.found)
                    continue;""",
        """                ++_p18TraceWorkers[self].stealAttempts;
                auto stolen = _queues[victim].steal();

                if (!stolen.found)
                    continue;
                ++_p18TraceWorkers[self].stealSuccesses;""")
    text = once(text,
        """            _inbox.parkUnlessChanged(observed);
        }
    }""",
        """            ++_p18TraceWorkers[self].parkAttempts;
            _inbox.parkUnlessChanged(observed);
        }
    }""")
    # Candidate-only retry classification, stored in the owning worker slot.
    # Every triggered retry ends in exactly one recovery, failed second scan,
    # or drained closed pool. Counters are read only after successful native join.
    if kind == "grace":
        text = once(text,
            """                idleRetries = 0;
                executeOne(local.value, self);""",
            """                if (idleRetries != 0)
                    ++_p18TraceWorkers[self].graceRecoveredLocal;
                idleRetries = 0;
                executeOne(local.value, self);""")
        text = once(text,
            """                idleRetries = 0;
                executeOne(batch[0], self);""",
            """                if (idleRetries != 0)
                    ++_p18TraceWorkers[self].graceRecoveredInbox;
                idleRetries = 0;
                executeOne(batch[0], self);""")
        text = once(text,
            """            if (foundWork)
            {
                idleRetries = 0;
                continue;
            }""",
            """            if (foundWork)
            {
                if (idleRetries != 0)
                    ++_p18TraceWorkers[self].graceRecoveredSteal;
                idleRetries = 0;
                continue;
            }""")
        text = once(text,
            """            if (_inbox.isDrained())
                break;""",
            """            if (_inbox.isDrained())
            {
                if (idleRetries != 0)
                    ++_p18TraceWorkers[self].graceDrainExits;
                break;
            }""")
        text = once(text,
            """                ++idleRetries;
                Thread.yield();""",
            """                ++idleRetries;
                ++_p18TraceWorkers[self].graceSearches;
                Thread.yield();""")
        text = once(text,
            """            idleRetries = 0;
            // Original M0 mutex/Condition/close/last-completion predicate,""",
            """            ++_p18TraceWorkers[self].graceFallbacks;
            idleRetries = 0;
            // Original M0 mutex/Condition/close/last-completion predicate,""")
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(
        "// AUTO-GENERATED P18 EVENT-ONLY RESEARCH COPY; NO PRODUCTION EDIT.\n" +
        text, encoding="utf8")
    print(f"P18 generated {kind} from reviewed source: {destination}")

if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("kind", choices=("control", "grace"))
    parser.add_argument("source", type=Path)
    parser.add_argument("destination", type=Path)
    args = parser.parse_args()
    instrument(args.source, args.destination, args.kind)
