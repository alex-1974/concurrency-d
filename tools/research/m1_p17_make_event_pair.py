#!/usr/bin/env python3
"""P17: instrument EXACT pinned original M0 and the P16.2 generated variant.

The only semantic change from each source is passive event counting. The
candidate must first have been generated by P16.2's reviewed source-pinned
generator. No extra mutex, cross-worker atomic or timing calls are added.
Counters are NOT trustworthy measures of time or portable overhead.
"""
import argparse
import hashlib
from pathlib import Path

M0 = "b7d8fafcb3179f00cba7e89e28c6d6b9b676353a"

def once(source, old, new):
    count = source.count(old)
    if count != 1:
        raise RuntimeError(f"P17 source drift: expected one anchor, found {count}: {old[:110]!r}")
    return source.replace(old, new, 1)

def instrument(path, destination, kind):
    raw = path.read_bytes()
    text = raw.decode("utf8")
    if kind == "control":
        blob = hashlib.sha1(f"blob {len(raw)}\0".encode() + raw).hexdigest()
        if blob != M0:
            raise RuntimeError(f"P17 original M0 changed: {blob}")
        oldmod = "module concurrency.internal.submission_pool;"
        module = "concurrency.research.m1_p17_control_pool"
        count_completed = "_completed"
    else:
        # Fail closed if this is not the exact-source variant generated by
        # m1_p16_2_make_atomic_completion.py from the pinned M0 source.
        if not text.startswith("// GENERATED P16.2 RESEARCH; NO PRODUCTION EDIT.\n"):
            raise RuntimeError("P17 candidate was not generated by P16.2 source guard")
        if f"// Original M0 Git blob {M0}\n" not in text[:180]:
            raise RuntimeError("P17 candidate does not identify reviewed M0 source")
        if text.count("atomicFetchAdd!(MemoryOrder.seq)(_completedAtomic") != 1:
            raise RuntimeError("P17 candidate completion semantics changed")
        oldmod = "module concurrency.research.m1_p16_2_pool;"
        module = "concurrency.research.m1_p17_atomic_pool"
        count_completed = "atomicLoad!(MemoryOrder.seq)(_completedAtomic)"

    text = once(text, oldmod, f"""module {module};

// P17 research-only per-worker counters and inbox sleeping-state bins.
// Read only after a successful native worker join.
align(64) private struct P17Worker
{{
    ulong localHits;
    ulong localMisses;
    ulong batchAttempts;
    ulong batchClaims;
    ulong batchTasks;
    ulong stealAttempts;
    ulong stealSuccesses;
    ulong parkAttempts;
    ulong executed;
}}
struct P17Snapshot
{{
    size_t workerCount;
    ulong localHits;
    ulong localMisses;
    ulong batchAttempts;
    ulong batchClaims;
    ulong batchTasks;
    ulong stealAttempts;
    ulong stealSuccesses;
    ulong parkAttempts;
    ulong parkWaits;
    ulong parkWaitsNoOutstanding;
    ulong parkWaitsWithOutstanding;
    ulong executed;
    ulong[16] workerExecuted;
}}
""")
    text = once(text,
        """    private size_t _parkCount;
    private bool _closed;""",
        """    private size_t _parkCount;
    private size_t _p17ParkNoOutstanding;
    private size_t _p17ParkWithOutstanding;
    private bool _closed;""")
    text = once(text,
        """                ++_parkCount;
                _changed.wait();""",
        f"""                ++_parkCount;
                // Same existing Condition Mutex protects accepted/queue and
                // the original completed field; the atomic version reads
                // the seq-cst completed counter with its normal protocol.
                const outstanding = _accepted - {count_completed};
                if (outstanding == 0)
                    ++_p17ParkNoOutstanding;
                else
                    ++_p17ParkWithOutstanding;
                _changed.wait();""")
    text = once(text,
        """    size_t parkCount()
    {
        synchronized (_mutex)
        {
            return _parkCount;
        }
    }

    bool isDrained()""",
        """    size_t parkCount()
    {
        synchronized (_mutex)
        {
            return _parkCount;
        }
    }

    void p17Read(ref P17Snapshot result)
    {
        synchronized (_mutex)
        {
            result.parkWaits = _parkCount;
            result.parkWaitsNoOutstanding = _p17ParkNoOutstanding;
            result.parkWaitsWithOutstanding = _p17ParkWithOutstanding;
        }
    }

    bool isDrained()""")
    text = once(text,
        """    private size_t _started;

    // Optional internal completion hook.""",
        """    private size_t _started;
    private P17Worker[] _p17Workers;

    // Optional internal completion hook.""")
    text = once(text,
        """        _workers = new Thread[workerCount];

        try""",
        """        _workers = new Thread[workerCount];
        _p17Workers = new P17Worker[workerCount];

        try""")
    text = once(text,
        """    /** Diagnostic only, used by race-oriented parking tests. */
    size_t parkCount()
    {
        return _inbox.parkCount();
    }

    private void executeOne(TaskRef task)""",
        """    /** Diagnostic only, used by race-oriented parking tests. */
    size_t parkCount()
    {
        return _inbox.parkCount();
    }

    P17Snapshot p17Snapshot()
    {
        P17Snapshot result;
        result.workerCount = _p17Workers.length;
        _inbox.p17Read(result);
        foreach (i, ref worker; _p17Workers)
        {
            if (i < result.workerExecuted.length)
                result.workerExecuted[i] = worker.executed;
            result.localHits += worker.localHits;
            result.localMisses += worker.localMisses;
            result.batchAttempts += worker.batchAttempts;
            result.batchClaims += worker.batchClaims;
            result.batchTasks += worker.batchTasks;
            result.stealAttempts += worker.stealAttempts;
            result.stealSuccesses += worker.stealSuccesses;
            result.parkAttempts += worker.parkAttempts;
            result.executed += worker.executed;
        }
        return result;
    }

    private void executeOne(TaskRef task, size_t self)""")
    text = once(text,
        """        dispatchTask(task);
        _inbox.completeOne();""",
        """        dispatchTask(task);
        _inbox.completeOne();
        ++_p17Workers[self].executed;""")
    for old, new in (
        ("executeOne(local.value);", "executeOne(local.value, self);"),
        ("executeOne(task);", "executeOne(task, self);"),
        ("executeOne(batch[0]);", "executeOne(batch[0], self);"),
        ("executeOne(stolen.value);", "executeOne(stolen.value, self);"),
    ):
        text = once(text, old, new)
    text = once(text,
        """            auto local = _queues[self].pop();
            if (local.found)
            {
                executeOne(local.value, self);
                continue;
            }""",
        """            auto local = _queues[self].pop();
            if (local.found)
            {
                ++_p17Workers[self].localHits;
                executeOne(local.value, self);
                continue;
            }
            ++_p17Workers[self].localMisses;""")
    text = once(text,
        """            const taken = _inbox.takeBatch(batch[]);
            if (taken != 0)
            {""",
        """            const taken = _inbox.takeBatch(batch[]);
            ++_p17Workers[self].batchAttempts;
            if (taken != 0)
            {
                ++_p17Workers[self].batchClaims;
                _p17Workers[self].batchTasks += taken;""")
    text = once(text,
        """                auto stolen = _queues[victim].steal();

                if (!stolen.found)
                    continue;""",
        """                ++_p17Workers[self].stealAttempts;
                auto stolen = _queues[victim].steal();

                if (!stolen.found)
                    continue;
                ++_p17Workers[self].stealSuccesses;""")
    text = once(text,
        """            _inbox.parkUnlessChanged(observed);
        }
    }""",
        """            ++_p17Workers[self].parkAttempts;
            _inbox.parkUnlessChanged(observed);
        }
    }""")
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(
        "// AUTO-GENERATED P17 EVENT-ONLY RESEARCH COPY; NO PRODUCTION EDIT.\n" +
        text, encoding="utf8")
    print(f"P17 generated {kind} from reviewed source: {destination}")

if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("kind", choices=("control", "atomic"))
    parser.add_argument("source", type=Path)
    parser.add_argument("destination", type=Path)
    args = parser.parse_args()
    instrument(args.source, args.destination, args.kind)
